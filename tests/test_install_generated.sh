#!/usr/bin/env bash
# test_install_generated.sh — dir #253 slice S1 (docs/specs/253-always-on-delivery-contract.md B1-B3, B2a, B10b):
# no Keel installer rewrites an entrypoint another tool generates. A context file whose FIRST line begins with
# `<!-- KEEL-GENERATED` is generator-owned (B1): install.sh leaves it byte-identical in every mode (B2),
# uninstall.sh leaves its rails in place (B2), doctor names it and gives the generator remedy (B3). An
# UNMARKED embedded KEEL-CORE block is auto-edited by `--link` only when the prior manifest recorded it as
# Keel's copy-install block (B2a); otherwise it is offered (terminal) or left untouched with a route.
# Each check runs in a tests/lib.sh sandbox, never the real ~/.claude.
# shellcheck source=tests/lib.sh
. "$(dirname "$0")/lib.sh" || { echo "lib.sh missing — refusing to run outside the sandbox" >&2; exit 1; }

git config --global --add safe.directory '*'

install="$REPO_ROOT/install.sh"
uninstall="$REPO_ROOT/uninstall.sh"
doctor="$REPO_ROOT/tools/doctor.sh"
have_script=1
command -v script >/dev/null 2>&1 || have_script=0
skip_tty() { printf '  SKIP  %s: no `script` binary on this host — the terminal branch is not exercised here\n' "$1"; }

core_block() { sed -n '/^<!-- KEEL-CORE-BEGIN/,/^<!-- KEEL-CORE-END/p' "$REPO_ROOT/CORE.md"; }
cksum_of() { cksum < "$1"; }
# arts FILE — count of `artifact=edit` records in a manifest (grep -c prints 0 on no match; its status is not read).
arts() { grep -c '^artifact=edit' "$1" || true; }
# mk_gen FILE KIND [IMPORT] — a generator-owned entrypoint (E7's shape: the marker on line 1, the comment closing on
# a later line, then the embedded rails and a downstream fence). KIND: block | drift | none | phrase | phrase-drift |
# both | trimmed-oldnote. `phrase*` carry the template's "always-loaded core" heading (the copy-mode ownership test).
mk_gen() {
  local f="$1" kind="$2" imp="${3:-}"
  {
    printf '%s\n' '<!-- KEEL-GENERATED — do NOT hand-edit: a regeneration overwrites this file.' \
      '     Generated by a stand-in generator; "@import" and "@ 9212408d" are prose in this header. -->' ''
    case "$kind" in
      block|drift|both|trimmed-oldnote) core_block ;;
      phrase|phrase-drift) cat "$REPO_ROOT/templates/CLAUDE.md" ;;
      none) printf 'Personal rules only — no Keel rails in this file.\n' ;;
    esac
    printf '\n%s\n%s\n%s\n' '<!-- KEEL-L1-BEGIN -->' 'personal layer text' '<!-- KEEL-L1-END -->'
    [ "$kind" = both ] && printf '\n%s\n' "$imp"
  } > "$f"
  case "$kind" in
    drift|phrase-drift) alter_block "$f" ;;
  esac
  if [ "$kind" = trimmed-oldnote ]; then
    # a git-rails-trimmed block carrying the LINKED note an older install's refresh wrote (test_core_block_currency.sh's shape)
    OLD_CRUMB='<!-- KEEL-NOGIT-BEGIN — generated by install.sh --link --no-git; not hand-edited (a re-run refreshes it) -->
**Git rails not installed on this machine** (`--no-git` install: the code/git rails are trimmed from
this always-on core). If git enters the workflow — STOP before the first git command and restore the
safety rails first: re-run `install.sh --link --with-git` in the Keel checkout.
<!-- KEEL-NOGIT-END -->' \
      awk '/KEEL-GIT-BEGIN/ { skip = 1; next } /KEEL-GIT-END/ { skip = 0; next } skip { next }
           /^## Secrets/ && !done { print ENVIRON["OLD_CRUMB"]; done = 1 } { print }' "$f" > "$f.new" && mv "$f.new" "$f"
  fi
}
# hand_copy FILE — a hand copy of templates/CLAUDE.md, its copy-path prose stripped as install does (an UNMARKED
# embedded block the copy-mode ownership test would accept).
hand_copy() { sed -e 's/ (TEMPLATE)$//' -e '/^> Copy this to your harness/d' "$REPO_ROOT/templates/CLAUDE.md" > "$1"; }
new_home() { mkdir -p "$SANDBOX/$1"; printf '%s' "$SANDBOX/$1"; }

gen_line='is generated by another tool (KEEL-GENERATED, line 1) — left untouched; change its sources and regenerate'

# --- A1: --link over a generator-owned CLAUDE.md (block identical, no manifest) is byte-identical ---------
h="$(new_home a1)"; mk_gen "$h/CLAUDE.md" block; before="$(cksum_of "$h/CLAUDE.md")"
run "$install" --link --home "$h" --no-hooks
check_status "A1: --link over a generated file → exit 0" 0 "$STATUS"
check_eq "A1: the generated file is byte-identical" "$before" "$(cksum_of "$h/CLAUDE.md")"
check_contains "A1: the output names KEEL-GENERATED" "$OUT" "KEEL-GENERATED"
check_contains "A1: B2's action line" "$OUT" "=    CLAUDE.md $gen_line"
check_absent "A1: no 'Migrate when ready'" "$OUT" "Migrate when ready"
check_absent "A1: no 'Add the line'" "$OUT" "Add the line"
check_absent "A1: no 'embedded rails swapped'" "$OUT" "embedded rails swapped"
check_contains "A1: B2's Verify line" "$OUT" "OK   CLAUDE.md is generated by another tool"
check_file "A1: the foreign-core sentinel is written as for a foreign file" "$h/.keel/foreign-core.claude"
check_absent "A1: the 'predates Keel' WARN is false for a file that carries rails" "$OUT" "predates Keel"
check_eq "A1: no artifact=edit record" 0 "$(arts "$h/.keel/install-manifest.claude")"
# second sample: BOTH the core import and a block — decides B2's bookkeeping (a link run records import-line for any file with the import)
h="$(new_home a1-both)"; mk_gen "$h/CLAUDE.md" both "@$h/keel/CORE.md"; before="$(cksum_of "$h/CLAUDE.md")"
run "$install" --link --home "$h" --no-hooks
check_eq "A1 both: byte-identical" "$before" "$(cksum_of "$h/CLAUDE.md")"
check_contains "A1 both: the Verify WARN says the rails load twice" "$OUT" "carries the rails twice"
check_absent "A1 both: no 'Remove the block' advice" "$OUT" "Remove the block"
check_eq "A1 both: the manifest has no artifact=edit line" 0 "$(arts "$h/.keel/install-manifest.claude")"

# --- A2: a drifted block under a terminal 'y' is still untouched, with no prompt --------------------------
if [ "$have_script" = 1 ]; then
  h="$(new_home a2)"; mk_gen "$h/CLAUDE.md" drift; before="$(cksum_of "$h/CLAUDE.md")"
  tty_run y "$install" --link --home "$h" --no-hooks
  check_eq "A2: drifted generated file, tty y → byte-identical" "$before" "$(cksum_of "$h/CLAUDE.md")"
  check_absent "A2: …and no [y/N] prompt" "$OUT" "[y/N]"
else skip_tty "A2"; fi

# --- A3: a generated file with no KEEL-CORE block gets no import line, and Verify says the rails will not load
h="$(new_home a3)"; mk_gen "$h/CLAUDE.md" none; before="$(cksum_of "$h/CLAUDE.md")"
run "$install" --link --home "$h" --no-hooks
check_eq "A3: no import line appended (byte-identical)" "$before" "$(cksum_of "$h/CLAUDE.md")"
check_absent "A3: no 'Add the line'" "$OUT" "Add the line"
check_contains "A3: the Verify WARN says the rails will NOT load" "$OUT" "is generated by another tool and carries no rails"
check_absent "A3: …not the OK line" "$OUT" "OK   CLAUDE.md is generated by another tool"

# --- A4: --codex and plain copy mode over a generated file --------------------------------------------------
if [ "$have_script" = 1 ]; then
  h="$(new_home a4-codex)"; mk_gen "$h/AGENTS.md" phrase-drift; before="$(cksum_of "$h/AGENTS.md")"
  tty_run y "$install" --codex --home "$h" --no-hooks
  check_eq "A4: --codex tty y over a generated AGENTS.md (phrase + drifted block) → byte-identical" "$before" "$(cksum_of "$h/AGENTS.md")"
  check_absent "A4: …no refresh offer" "$OUT" "[y/N]"
  check_eq "A4: …no artifact=edit record (--codex)" 0 "$(arts "$h/.keel/install-manifest.codex")"
  h="$(new_home a4-copy)"; mk_gen "$h/CLAUDE.md" phrase-drift; before="$(cksum_of "$h/CLAUDE.md")"
  tty_run y "$install" --home "$h" --no-hooks
  check_eq "A4: plain copy mode tty y over a generated CLAUDE.md → byte-identical" "$before" "$(cksum_of "$h/CLAUDE.md")"
  check_absent "A4: …no refresh offer" "$OUT" "[y/N]"
  check_eq "A4: …no artifact=edit record (copy)" 0 "$(arts "$h/.keel/install-manifest.claude")"
else skip_tty "A4 tty halves"; fi
h="$(new_home a4-nophrase)"; mk_gen "$h/AGENTS.md" block; before="$(cksum_of "$h/AGENTS.md")"
run "$install" --codex --home "$h" --no-hooks
check_eq "A4: --codex over a generated AGENTS.md without the phrase → byte-identical" "$before" "$(cksum_of "$h/AGENTS.md")"
check_contains "A4: …B2's line" "$OUT" "=    AGENTS.md $gen_line"
check_absent "A4: …and not 'predates Keel'" "$OUT" "predates Keel"
check_eq "A4: …no artifact=edit record" 0 "$(arts "$h/.keel/install-manifest.codex")"

# --- A5: uninstall leaves a generated file's rails in place -------------------------------------------------
h="$(new_home a5)"
run "$install" --link --home "$h" --no-hooks
mk_gen "$h/CLAUDE.md" block; before="$(cksum_of "$h/CLAUDE.md")"
run "$uninstall" --home "$h" --dry-run
check_absent "A5: --dry-run prints no 'would strip' for a generated file" "$OUT" "would strip"
run "$uninstall" --home "$h" --yes
check_status "A5: uninstall --yes → exit 0" 0 "$STATUS"
check_eq "A5: the generated file is byte-identical" "$before" "$(cksum_of "$h/CLAUDE.md")"
check_contains "A5: the output says the rails were left in place" "$OUT" "is generated by another tool — its rails were left in place; remove them at the generator"
check_absent "A5: no strip line" "$OUT" "stripped the Keel rails"
# a home holding ONLY a generated file and no manifest: "no Keel install here", never advised to run install.sh
h="$(new_home a5-only)"; mk_gen "$h/CLAUDE.md" block; before="$(cksum_of "$h/CLAUDE.md")"
run "$uninstall" --home "$h" --dry-run
check_status "A5 only: --dry-run → exit 0" 0 "$STATUS"
check_absent "A5 only: --dry-run prints no 'would strip'" "$OUT" "would strip"
check_absent "A5 only: --dry-run advises no install.sh run" "$OUT" "Record a manifest first"
run "$uninstall" --home "$h" --yes
check_status "A5 only: --yes → exit 0 (no refusal)" 0 "$STATUS"
check_absent "A5 only: reports no Keel install to repair" "$OUT" "holds a Keel install"
check_absent "A5 only: advises no install.sh run" "$OUT" "Record a manifest first"
check_eq "A5 only: byte-identical" "$before" "$(cksum_of "$h/CLAUDE.md")"

# --- A6 (guards, hold today): line 1 only ---------------------------------------------------------------------
h="$(new_home a6-line2)"; printf '<!-- a note -->\n<!-- KEEL-GENERATED -->\nmy rules\n' > "$h/CLAUDE.md"
run "$install" --link --home "$h" --no-hooks
check_contains "A6 (i): the marker on line 2 is prose — the import is appended" "$(cat "$h/CLAUDE.md")" "keel/CORE.md"
h="$(new_home a6-word)"; printf '# Notes on KEEL-GENERATED files\nmy rules\n' > "$h/CLAUDE.md"
run "$install" --link --home "$h" --no-hooks
check_contains "A6 (iii): the word on line 1, not at its start, is not the marker — the import is appended" "$(cat "$h/CLAUDE.md")" "keel/CORE.md"
h="$(new_home a6-migrate)"
run "$install" --home "$h" --no-hooks
run "$install" --link --home "$h" --no-hooks
check_contains "A6 (ii): a Keel copy wrapper still migrates" "$OUT" "embedded rails swapped for the import line"

# --- A7: a symlinked context file is read through the link; both stay as they are ----------------------------
h="$(new_home a7)"; mkdir -p "$SANDBOX/a7-dots"; mk_gen "$SANDBOX/a7-dots/CLAUDE.md" block; ln -s "$SANDBOX/a7-dots/CLAUDE.md" "$h/CLAUDE.md"
before="$(cksum_of "$SANDBOX/a7-dots/CLAUDE.md")"
run "$install" --link --home "$h" --no-hooks
check_link "A7: CLAUDE.md is still a link" "$h/CLAUDE.md"
check_eq "A7: the link's target is byte-identical" "$before" "$(cksum_of "$SANDBOX/a7-dots/CLAUDE.md")"

# --- A8: doctor names a generated file and gives the generator remedy --------------------------------------
doc_line() { grep -F "$2" <<<"$1" | head -n1 || true; }
h="$(new_home a8)"
run "$install" --link --home "$h" --no-hooks
mk_gen "$h/CLAUDE.md" block
run "$doctor" --install "$h"
check_contains "A8: the rails line names the generated file" "$(doc_line "$OUT" 'core rails')" "generated"
mk_gen "$h/CLAUDE.md" drift
run "$doctor" --install "$h"
l="$(doc_line "$OUT" W-CORE-DRIFT)"
check_contains "A8: drifted → W-CORE-DRIFT says regenerate" "$l" "regenerate"
check_absent "A8: …and names no install.sh" "$l" "install.sh"
mk_gen "$h/CLAUDE.md" none
run "$doctor" --install "$h"
l="$(doc_line "$OUT" W-RAILS-UNWIRED)"
check_contains "A8: neither block nor import → W-RAILS-UNWIRED says regenerate" "$l" "regenerate"
check_absent "A8: …and names no install.sh" "$l" "install.sh"
mk_gen "$h/CLAUDE.md" both "@$h/keel/CORE.md"
run "$doctor" --install "$h"
l="$(doc_line "$OUT" W-RAILS-DOUBLE)"
check_contains "A8: import AND block → W-RAILS-DOUBLE names the generator" "$l" "generator"
check_absent "A8: …never 'remove the block'" "$l" "remove the block"
mk_gen "$h/CLAUDE.md" trimmed-oldnote
run "$doctor" --install "$h"
l="$(doc_line "$OUT" W-CORE-DRIFT)"
check_contains "A8: trimmed block with the older linked note → W-CORE-DRIFT says regenerate" "$l" "regenerate"
check_absent "A8: …and names no install.sh" "$l" "install.sh"

# --- A9: the documents ---------------------------------------------------------------------------------------
adapting="$(cat "$REPO_ROOT/ADAPTING.md")"
sec="$(awk '/^## Generating your entrypoints yourself/ { f = 1; print; next } f && /^## / { exit } f' "$REPO_ROOT/ADAPTING.md")"
check_contains "A9: ADAPTING.md has the generator section" "$adapting" "## Generating your entrypoints yourself"
for tok in KEEL-GENERATED KEEL-CORE KEEL-GIT KEEL-NOGIT KEEL-MANAGER-MERGES; do
  check_contains "A9: the generator section names $tok" "$sec" "$tok"
done
check_contains "A9: keel-setup.md carries B2's sentence" "$(grep -F KEEL-GENERATED "$REPO_ROOT/commands/keel-setup.md" || true)" "KEEL-GENERATED"

# --- A10: a second run is identical -------------------------------------------------------------------------
h="$(new_home a10)"; mk_gen "$h/CLAUDE.md" block
run "$install" --link --home "$h" --no-hooks; first="$OUT"; c1="$(cksum_of "$h/CLAUDE.md")"
run "$install" --link --home "$h" --no-hooks
check_eq "A10: two runs leave the file identical" "$c1" "$(cksum_of "$h/CLAUDE.md")"
check_eq "A10: …and print the same action line" "$(grep -F "CLAUDE.md $gen_line" <<<"$first")" "$(grep -F "CLAUDE.md $gen_line" <<<"$OUT")"
check_eq "A10: …no edit record" 0 "$(arts "$h/.keel/install-manifest.claude")"

# --- A10a: B2a — an unrecorded block (a hand copy, no manifest) is offered, never auto-swapped ----------------
h="$(new_home a10a)"; hand_copy "$h/CLAUDE.md"; before="$(cksum_of "$h/CLAUDE.md")"
run "$install" --link --home "$h" --no-hooks
check_eq "A10a: off a terminal → byte-identical" "$before" "$(cksum_of "$h/CLAUDE.md")"
check_contains "A10a: …the line says Keel did not record the block" "$OUT" "did not record"
check_contains "A10a: …and carries the migrate route" "$OUT" "replace the KEEL-CORE block with the line"
check_absent "A10a: …no swap line" "$OUT" "embedded rails swapped"
if [ "$have_script" = 1 ]; then
  h="$(new_home a10a-tty)"; hand_copy "$h/CLAUDE.md"
  tty_run y "$install" --link --home "$h" --no-hooks
  check_contains "A10a tty: the offer line says Keel did not record the block" "$OUT" "did not record"
  check_absent "A10a tty: answered y → the block is swapped for the import line" "$(cat "$h/CLAUDE.md")" "KEEL-CORE-BEGIN"
  check_contains "A10a tty: …the import is there" "$(cat "$h/CLAUDE.md")" "keel/CORE.md"
  # A10c (iii): an EMPTY answer keeps the file (default no)
  h="$(new_home a10c-empty)"; hand_copy "$h/CLAUDE.md"; before="$(cksum_of "$h/CLAUDE.md")"
  tty_run "" "$install" --link --home "$h" --no-hooks
  check_eq "A10c (iii): an empty answer leaves the file byte-identical" "$before" "$(cksum_of "$h/CLAUDE.md")"
else skip_tty "A10a tty / A10c (iii)"; fi

# --- A10b: B2a — a link manifest does not make a block recorded ---------------------------------------------
h="$(new_home a10b)"
run "$install" --link --home "$h" --no-hooks
hand_copy "$h/CLAUDE.md"; before="$(cksum_of "$h/CLAUDE.md")"
run "$install" --link --home "$h" --no-hooks
check_eq "A10b: a link manifest + an unrecorded hand copy → byte-identical" "$before" "$(cksum_of "$h/CLAUDE.md")"
check_contains "A10b: …did not record" "$OUT" "did not record"
# the duplicate-removal branch: an unrecorded import + identical block is left as it is, with no offer
h="$(new_home a10b-dup)"
run "$install" --link --home "$h" --no-hooks
hand_copy "$h/CLAUDE.md"; printf '\n@%s/keel/CORE.md\n' "$h" >> "$h/CLAUDE.md"
before="$(cksum_of "$h/CLAUDE.md")"
run "$install" --link --home "$h" --no-hooks
check_eq "A10b dup: off a terminal → byte-identical" "$before" "$(cksum_of "$h/CLAUDE.md")"
check_absent "A10b dup: …no removal line" "$OUT" "removed the embedded rails block"
check_contains "A10b dup: …the left-untouched line says Keel did not record it" "$OUT" "did not record"
if [ "$have_script" = 1 ]; then
  tty_run y "$install" --link --home "$h" --no-hooks
  check_eq "A10b dup: under tty y → still byte-identical" "$before" "$(cksum_of "$h/CLAUDE.md")"
  check_absent "A10b dup: …no [y/N] offer" "$OUT" "[y/N]"
  check_absent "A10b dup: …no removal line" "$OUT" "removed the embedded rails block"
else skip_tty "A10b dup tty"; fi

# --- A10b': a copy manifest WITHOUT the core-block record is unrecorded too --------------------------------------
h="$(new_home a10bp)"; core_block > "$h/CLAUDE.md"; before="$(cksum_of "$h/CLAUDE.md")"
run "$install" --home "$h" --no-hooks
check_contains "A10b': the plain install recorded layout=copy" "$(cat "$h/.keel/install-manifest.claude")" "layout=copy"
check_eq "A10b': …and found the file foreign (no edit record)" 0 "$(arts "$h/.keel/install-manifest.claude")"
run "$install" --link --home "$h" --no-hooks
check_eq "A10b': --link over it → byte-identical" "$before" "$(cksum_of "$h/CLAUDE.md")"
check_contains "A10b': …did not record" "$OUT" "did not record"

# --- A10c: a RECORDED block still migrates ------------------------------------------------------------------------
h="$(new_home a10c-i)"
run "$install" --home "$h" --no-hooks
check_eq "A10c (i): the copy install recorded core-block" 1 "$(arts "$h/.keel/install-manifest.claude")"
run "$install" --link --home "$h" --no-hooks
check_contains "A10c (i): --link swaps the recorded block with no question" "$OUT" "embedded rails swapped for the import line"
h="$(new_home a10c-ii)"
run "$install" --home "$h" --no-hooks
alter_block "$h/CLAUDE.md"; before="$(cksum_of "$h/CLAUDE.md")"
run "$install" --link --home "$h" --no-hooks
check_eq "A10c (ii): a recorded but EDITED block → byte-identical (the record never overrides the bytes)" "$before" "$(cksum_of "$h/CLAUDE.md")"
h="$(new_home a10c-iv)"
run "$install" --home "$h" --no-hooks
printf '\n@%s/keel/CORE.md\n' "$h" >> "$h/CLAUDE.md"
run "$install" --link --home "$h" --no-hooks
check_contains "A10c (iv): a recorded block + a hand-added import → the duplicate is removed" "$OUT" "removed the embedded rails block"
check_absent "A10c (iv): …no KEEL-CORE block remains" "$(cat "$h/CLAUDE.md")" "KEEL-CORE-BEGIN"

summary
